// Rebuilds src/data/recipePhotos.ts from the files in assets/recipes/.
// Usage: npm run photos   (after adding assets/recipes/<recipe-id>.jpg)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const ids = fs
  .readdirSync(path.join(root, 'assets/recipes'))
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort()
  .map((f) => [f.replace(/\.[^.]+$/, ''), f]);

const out = `import type { ImageSourcePropType } from 'react-native';

/**
 * Photos bundled with the app, keyed by recipe id. Recipes without an entry
 * (and without an \`imageUrl\`) fall back to their emoji on a tinted background.
 * To add one: drop \`assets/recipes/<recipe-id>.jpg\` (≈720×900) and run \`npm run photos\`.
 * This file is generated by scripts/gen-photo-index.mjs.
 */
export const RECIPE_PHOTOS: Record<string, ImageSourcePropType> = {
${ids.map(([id, f]) => `  '${id}': require('../../assets/recipes/${f}'),`).join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src/data/recipePhotos.ts'), out);
console.log(`recipePhotos.ts: ${ids.length} photos`);
